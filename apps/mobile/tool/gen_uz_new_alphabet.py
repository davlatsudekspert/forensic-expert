"""Generates AppLocalizationsUzNew (uz UI strings in the new alphabet,
O‘RQ-1184). Run right after `flutter gen-l10n`. Idempotent."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / 'lib/core/l10n/generated/app_localizations.dart').read_text(encoding='utf-8')
body = src[src.index('abstract class AppLocalizations'):]
members = re.findall(r'^  String (get )?(\w+)(\([^)]*\))?;', body, re.M | re.S)
out = ['// GENERATED by tool/gen_uz_new_alphabet.py — do not edit.',
       '// ignore_for_file: type=lint',
       "import '../uz_alphabet.dart';",
       "import 'app_localizations_uz.dart';",
       '',
       '/// O‘zbekcha UI matnlari yangi alifboda (O‘RQ-1184).',
       'class AppLocalizationsUzNew extends AppLocalizationsUz {',
       "  AppLocalizationsUzNew() : super('uz');",
       '']
n = 0
for get, name, params in members:
    if get:
        out += ['  @override', f'  String get {name} => toUzNewAlphabet(super.{name});', '']
    else:
        p = params[1:-1].strip()
        names = [re.split(r'\s+', x.strip())[-1] for x in p.split(',') if x.strip()]
        out += ['  @override', f'  String {name}({p}) =>',
                f'      toUzNewAlphabet(super.{name}({", ".join(names)}));', '']
    n += 1
out.append('}')
(root / 'lib/core/l10n/generated/app_localizations_uz_new.dart').write_text('\n'.join(out) + '\n', encoding='utf-8')
print('gen_uz_new_alphabet:', n, 'members')
