#!/usr/bin/env python3
"""«Test o‘tkazish» mavzu ro‘yxati uchun takrorlar jadvali → Dart.

«Darslar» (lesson_topics) qanday ko‘rsatsa, test mavzulari ham shunday
ko‘rinsin: bir fakultet ichida bir xil prezentatsiyani ochadigan takror
mavzu (lesson_topics.hidden = true) va `ktp26-u-*` (KTP takrorlarini
birlashtirish uchun ichki ro‘yxat; ustozga fakultet mavzusi sifatida
ko‘rsatiladi) — ro‘yxatda o‘sha mavzu bor bo‘lsa yashiriladi.

Manba: tools/lessons/build_lessons_seed.py bilan bir xil reja
(docs/curriculum/*.md + origin/slides-out:out/aliases.json).

  python3 tools/class_quiz/gen_topic_catalog.py \
      --server-titles apps/mobile/test/fixtures/class_topics_server.json \
      --out apps/mobile/lib/domain/class_quiz/class_topic_duplicates.dart
"""
import argparse
import collections
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools/lessons"))
sys.path.insert(0, str(ROOT / "tools/slides"))
import build_lessons_seed as seed  # noqa: E402
import topics  # noqa: E402


def lesson_rows(ref: str):
    names = subprocess.run(["git", "ls-tree", "--name-only", ref, "out/"], cwd=ROOT,
                           check=True, capture_output=True, text=True).stdout.split()
    deck_ids = {n[4:-5] for n in names if n.endswith(".json") and not n.endswith(".en.json")
                and ".unvalidated" not in n and not n.endswith("aliases.json")}
    aliases = json.loads(seed.git_show(ref, "out/aliases.json"))["alias"]
    plan = topics.parse_topics() + topics.parse_topics(topics.BIOETIKA) + topics.parse_ktp()
    order = list(seed.COURSES)
    plan.sort(key=lambda t: order.index(t["course"]) if t["course"] in seed.COURSES else len(order))
    rows, seen = [], set()
    for t in plan:
        if t["course"] not in seed.COURSES:
            continue
        did = t["id"] if t["id"] in deck_ids else aliases.get(t["id"])
        if did not in deck_ids:
            continue
        course = seed.COURSES[t["course"]]
        hidden = (course, did) in seen
        seen.add((course, did))
        rows.append((t["id"], did, course, hidden, t["title"]))
    return rows


def covered_by(rows):
    visible = collections.defaultdict(list)  # (course, deck) -> tid
    by_deck = collections.defaultdict(list)  # deck -> visible tids
    for tid, did, course, hidden, _ in rows:
        if not hidden:
            visible[(course, did)].append(tid)
            by_deck[did].append(tid)
    out = {}
    for tid, did, course, hidden, _ in rows:
        if hidden and visible[(course, did)]:
            out[tid] = sorted(visible[(course, did)])
    lesson_ids = {r[0] for r in rows}
    for did, tids in by_deck.items():
        if did.startswith("ktp26-u-") and did not in lesson_ids:
            out[did] = sorted(tids)
    return dict(sorted(out.items()))


STUB_RE = re.compile(r"^\W*(amaliy\s+mashg.?ulot|ma.?ruza|seminar)\W*$", re.I)


def stub_titles(rows, server_json):
    """Serverdagi nomi faqat «Amaliy mashg‘ulot» bo‘lgan mavzular → o‘quv rejadagi to‘liq nom."""
    if not server_json:
        return {}
    srv = {x["topic_id"]: x["title"] for x in json.loads(pathlib.Path(server_json).read_text(encoding="utf-8"))
           if "~" not in x["topic_id"]}
    out = {}
    for tid, _, _, _, title in rows:
        if tid in srv and STUB_RE.match(srv[tid]) and not STUB_RE.match(title):
            out[tid] = title.strip()
    return dict(sorted(out.items()))


def dart_str(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def dart(table, titles) -> str:
    lines = [
        "// GENERATED by tools/class_quiz/gen_topic_catalog.py — qo‘lda o‘zgartirmang.",
        "//",
        "// Mavzu → uni «Darslar»da o‘rnini bosadigan mavzu(lar). Ro‘yxatda shulardan",
        "// biri bo‘lsa, mavzu «Test o‘tkazish» ro‘yxatida ko‘rsatilmaydi (takror).",
        "const Map<String, List<String>> classTopicCoveredBy = {",
    ]
    for k, v in table.items():
        items = ", ".join(f"'{x}'" for x in v)
        line = f"  '{k}': [{items}],"
        if len(line) > 80:
            lines.append(f"  '{k}': [")
            lines += [f"    '{x}'," for x in v]
            lines.append("  ],")
        else:
            lines.append(line)
    lines.append("};")
    lines += [
        "",
        "// Serverda nomi faqat «Amaliy mashg‘ulot» bo‘lgan mavzular: o‘quv rejadagi",
        "// to‘liq nom (docs/curriculum). Faqat shunday qisqa nom o‘rniga qo‘llanadi.",
        "const Map<String, String> classTopicPlanTitles = {",
    ]
    for k, v in titles.items():
        lines.append(f"  '{k}':")
        lines.append(f"      {dart_str(v)},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--git-ref", default="origin/slides-out")
    ap.add_argument("--out", required=True)
    ap.add_argument("--server-titles", default=None,
                    help="class_topics() javobi (JSON: topic_id, title) — qisqa nomlarni aniqlash uchun")
    a = ap.parse_args()
    rows = lesson_rows(a.git_ref)
    table = covered_by(rows)
    pathlib.Path(a.out).write_text(dart(table, stub_titles(rows, a.server_titles)), encoding="utf-8")
    print(f"{len(table)} mavzu → {a.out}")


if __name__ == "__main__":
    main()
